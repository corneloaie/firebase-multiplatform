# Parameter types that only exist on Android and the JVM: the overload is left out (see api/android-sdk/exclusions.txt).
PLATFORM_TYPES = {'Date'}

# Bodies that use the SDK's internal model (protos, model field paths), by function name and parameter types.
OVERRIDES = {
    ('constant', ('String',)): ('Constant(value)', 'A constant string.'),
    ('constant', ('Number',)): ('Constant(value)', 'A constant number: an integer for `Byte`, `Short`, `Int` and `Long`, a double otherwise.'),
    ('constant', ('Timestamp',)): ('Constant(value)', 'A constant timestamp.'),
    ('constant', ('Boolean',)): ('BooleanConstant(Constant(value))', 'A constant boolean, which is a condition.'),
    ('constant', ('GeoPoint',)): ('Constant(value)', 'A constant geographic point.'),
    ('constant', ('ByteArray',)): ('Constant(value)', 'Constant bytes.'),
    ('constant', ('Blob',)): ('Constant(value)', 'Constant bytes.'),
    ('constant', ('DocumentReference',)): ('Constant(ref)', 'A constant document reference.'),
    ('constant', ('VectorValue',)): ('Constant(value)', 'A constant vector.'),
    ('nullValue', ()): ('NULL', 'The constant null.'),
    ('vector', ('DoubleArray',)): ('Constant(FieldValue.vector(vector))', 'A constant vector of [vector].'),
    ('vector', ('VectorValue',)): ('Constant(vector)', 'The constant vector [vector].'),
    ('field', ('String',)): ('Field.fromDotSeparatedPath(name)', 'A reference to the field at the `.`-separated path [name] (`__name__`, `__create_time__` and `__update_time__` are the document\'s name and times).'),
    ('field', ('FieldPath',)): ('Field.of(fieldPath)', 'A reference to the field at [fieldPath].'),
    ('variable', ('String',)): ('Variable(name)', 'A reference to the variable [name], bound by the define stage or by `arrayFilter` and `arrayTransform`.'),
}

# Helpers of the SDK's companion that this file defines itself (see COMPANION_HELPERS).
REPLACED_HELPERS = {'toExprOrConstant', 'pojoToExprOrConstant', 'toExpr', 'toArrayOfExprOrConstant'}

COMPANION_HELPERS = '''        /** [value] as an expression: itself if it is one, otherwise a constant (a map or a list as a `map` or `array` function). */
        internal fun toExprOrConstant(value: Any?): Expression = when (value) {
            null -> NULL

            is Expression -> value

            is String -> constant(value)

            is Number -> constant(value)

            is Timestamp -> constant(value)

            is Boolean -> constant(value)

            is GeoPoint -> constant(value)

            is Blob -> constant(value)

            is DocumentReference -> constant(value)

            is ByteArray -> constant(value)

            is VectorValue -> constant(value)

            is Map<*, *> -> map(
                value.entries.flatMap { (key, entryValue) ->
                    require(key is String) { "Maps with non-string keys are not supported" }
                    listOf(constant(key), toExprOrConstant(entryValue))
                }.toTypedArray(),
            )

            is List<*> -> array(value)

            is Pipeline -> PipelineValueExpression(value)

            else -> throw IllegalArgumentException("Unknown type: $value")
        }

        internal fun toArrayOfExprOrConstant(others: Array<out Any>): Array<out Expression> = others.map(::toExprOrConstant).toTypedArray()

        private fun toArrayOfExprOrConstant(others: Iterable<Any>): Array<out Expression> = others.map(::toExprOrConstant).toTypedArray()

        private val NULL: Expression = Constant(null)
'''

EXPRESSION_KDOC = '''/**
 * An expression of the pipeline API, mirroring `com.google.firebase.firestore.pipeline.Expression` from the Firebase
 * Android SDK: a field reference, a constant, or a function of the pipeline backend over other expressions. The functions
 * of the companion object create them; the member functions apply the companion function of the same name to this
 * expression, as its first argument. A function taking a field name instead of an expression applies to that field;
 * a value of type `Any` becomes a constant (see [constant]).
 *
 * Expressions are evaluated by the backend when the [com.google.firebase.firestore.Pipeline] runs; building them does
 * not check their types.
 */'''

AGGREGATE_KDOC = '''/**
 * An aggregate function of the pipeline API, mirroring `com.google.firebase.firestore.pipeline.AggregateFunction` from
 * the Firebase Android SDK: computed over the input documents (or over each group) by the aggregate stage; name the
 * result with [alias].
 */'''


def read_ref() -> str:
    with open(os.path.join(ROOT, 'gradle.properties')) as properties:
        for line in properties:
            if line.startswith('androidSdk.apiRef='):
                return line.split('=', 1)[1].strip()
    raise SystemExit('androidSdk.apiRef is not set in gradle.properties')


def fetch_sources(ref: str, source_dir: str | None) -> dict[str, str]:
    sources = {}
    cache = os.path.join(MODULE, 'build', 'pipeline-codegen', ref)
    for name in SOURCES:
        if source_dir:
            path = os.path.join(source_dir, name)
        else:
            path = os.path.join(cache, name)
            if not os.path.exists(path):
                os.makedirs(cache, exist_ok=True)
                url = f'https://raw.githubusercontent.com/firebase/firebase-android-sdk/{ref}/{SOURCE_PATH}/{name}'
                with urllib.request.urlopen(url) as response, open(path + '.part', 'wb') as out:
                    out.write(response.read())
                os.replace(path + '.part', path)
        with open(path, encoding='utf-8') as source:
            sources[name] = strip_comments(source.read())
    return sources


def drop_evaluation_functions(body: str) -> str:
    """`FunctionExpression(name, evaluateX, args)` becomes `FunctionExpression(name, args)`, at any depth."""
    result, i = [], 0
    pattern = re.compile(r'\b(Boolean)?FunctionExpression\(')
    while True:
        match = pattern.search(body, i)
        if not match:
            result.append(body[i:])
            return ''.join(result)
        open_paren = match.end() - 1
        close = matching(body, open_paren)
        args = [drop_evaluation_functions(arg) for arg in split_top_level(body[open_paren + 1:close - 1])]
        if len(args) >= 2 and re.fullmatch(r'\w+', args[1]) and not args[1].startswith('"'):
            args.pop(1)
        result.append(body[i:open_paren + 1] + ', '.join(args) + ')')
        i = close


def render_parameters(function: Function) -> str:
    return ', '.join(('vararg ' if p.vararg else '') + f'{p.name}: {p.type}' for p in function.parameters)


def call_parts(body: str) -> tuple[str, list[str]] | None:
    """The callee and arguments of [body] when it is a single call."""
    match = re.match(r'((?:[A-Z]\w*\.)*\w+)\(', body)
    if not match:
        return None
    close = matching(body, match.end() - 1)
    if close != len(body):
        return None
    return match.group(1), split_top_level(body[match.end():close - 1])


def describe_argument(arg: str, function: Function, field_position: bool) -> str:
    parameters = {p.name: p for p in function.parameters}
    arg = arg.strip()
    spread = arg.startswith('*')
    arg = arg.lstrip('*')
    if arg == 'this':
        return 'this expression'
    if arg in parameters:
        if field_position and parameters[arg].type == 'String':
            return f'the field [{arg}]'
        return f'[{arg}]'
    call = call_parts(arg)
    if call:
        callee, args = call
        inner = describe_argument(args[0], function, False) if len(args) == 1 else None
        simple = callee.split('.')[-1]
        if simple == 'field' and inner:
            return 'the field ' + inner.removeprefix('the field ')
        if simple in ('constant', 'toExprOrConstant', 'toArrayOfExprOrConstant') and inner:
            return inner
        if simple == 'array' and inner:
            return 'the array ' + inner
        if simple == 'vector' and inner:
            return 'the vector ' + inner
    if spread:
        return f'`*{arg}`'
    return f'`{arg}`'


def join_descriptions(parts: list[str]) -> str:
    if not parts:
        return ''
    if len(parts) == 1:
        return parts[0]
    return ', '.join(parts[:-1]) + ' and ' + parts[-1]


def describe(function: Function, body: str) -> str:
    call = call_parts(body)
    if call:
        callee, args = call
        simple = callee.split('.')[-1]
        if simple in ('FunctionExpression', 'BooleanFunctionExpression', 'AggregateFunction') and args and args[0].startswith('"'):
            name = args[0].strip('"')
            kind = {'FunctionExpression': 'function', 'BooleanFunctionExpression': 'condition', 'AggregateFunction': 'aggregate'}[simple]
            described = [describe_argument(a, function, i == 0) for i, a in enumerate(args[1:])]
            return f'The `{name}` {kind}' + (f' of {join_descriptions(described)}.' if described else '.')
        if simple in ('FunctionExpression', 'BooleanFunctionExpression', 'AggregateFunction'):
            # rawFunction, rawAggregate: the name is a parameter
            described = [describe_argument(a, function, False) for a in args[1:]]
            return f'The backend function [{args[0]}]' + (f' of {join_descriptions(described)}.' if described else '.')
        if simple == 'AliasedExpression':
            return f'This expression under the alias [{args[0]}]: its name in the output documents.'
        if simple == 'AliasedAggregate':
            return f'This aggregate under the alias [{args[0]}]: its name in the output documents.'
        if callee.startswith(('Companion.', 'Expression.')) or callee == simple:
            described = [describe_argument(a, function, False) for a in args]
            return f'[{simple}] of {join_descriptions(described)}.' if described else f'[{simple}].'
        if callee.startswith(('AggregateFunction.', 'Ordering.')):
            owner = callee.split('.')[0]
            described = [describe_argument(a, function, False) for a in args]
            return f'[{owner}.{simple}] of {join_descriptions(described)}.'
    return f'Mirrors `{function.name}` of the Android SDK.'


class Generator:
    def __init__(self, class_name: str, functions_by_scope: dict[str, list[Function]]):
        self.class_name = class_name
        self.scopes = functions_by_scope
        self.errors = []
        self.skipped = []

    def return_type(self, function: Function, body: str) -> str | None:
        if function.return_type:
            return function.return_type
        call = call_parts(body)
        if call:
            callee, _ = call
            simple = callee.split('.')[-1]
            if simple == 'BooleanFunctionExpression':
                return 'BooleanExpression'
            if simple in ('FunctionExpression', 'AggregateFunction', 'AliasedAggregate', 'AliasedExpression', 'Ordering'):
                return 'Expression' if simple == 'FunctionExpression' else simple
            owner = callee.split('.')[0] if '.' in callee else None
            candidates = [f for scope in self.scopes.values() for f in scope if f.name == simple and f.return_type]
            if owner in ('AggregateFunction', 'Ordering'):
                return owner
            types = {f.return_type for f in candidates}
            if len(types) == 1:
                return types.pop()
        self.errors.append(f'{self.class_name}.{function.name}({render_parameters(function)}): no return type; add an override')
        return None

    def render(self, function: Function, indent: str, static: bool) -> str | None:
        key = (function.name, tuple(p.type for p in function.parameters))
        if PLATFORM_TYPES & {p.type for p in function.parameters}:
            self.skipped.append(f'{self.class_name}{".Companion" if static else ""}.{function.name}({", ".join(key[1])})')
            return None
        doc = None
        if key in OVERRIDES:
            body, doc = OVERRIDES[key]
        elif key == ('asBoolean', ()):
            body = None  # rendered as a `when` below
        elif not function.expression_body:
            body = function.body.strip()
            if body.startswith('return ') and not re.search(r'\b(when|if|for|while|val|var)\b', body):
                body = body[len('return '):]
            else:
                self.errors.append(f'{self.class_name}.{function.name}({render_parameters(function)}): block body; add an override')
                return None
        else:
            body = function.body
        if body is not None:
            body = drop_evaluation_functions(body)
            for internal in ('encodeValue', 'Values.', 'ModelFieldPath', 'KEY_PATH', 'TIME_PATH', 'internalPath', 'notImplemented', 'evaluate', 'toProto'):
                if internal in body:
                    self.errors.append(f'{self.class_name}.{function.name}({render_parameters(function)}): uses {internal}; add an override')
                    return None
        return_type = self.return_type(function, body) if body is not None else function.return_type
        if return_type is None:
            return None
        if doc is None:
            doc = describe(function, body) if body is not None else 'This expression as a condition: unchanged if it is one, otherwise evaluated as a boolean.'
        if '@Beta' in function.annotations:
            doc += ' Beta in the Android SDK.'
        visibility = 'public' if function.is_public else next(m for m in function.modifiers if m in ('internal', 'private', 'protected'))
        lines = [f'{indent}/** {doc} */'] if function.is_public else []
        if static and function.is_public:
            lines.append(f'{indent}@JvmStatic')
        signature = f'{indent}{visibility} fun {function.name}({render_parameters(function)}): {return_type}'
        if body is None:
            lines.append(signature + ' = when (this) {')
            lines.append(f'{indent}    is BooleanExpression -> this')
            lines.append(f'{indent}    is Constant -> BooleanConstant(this)')
            lines.append(f'{indent}    is Field -> BooleanField(this)')
            lines.append(f'{indent}    else -> BooleanFunctionExpression(this)')
            lines.append(f'{indent}}}')
        else:
            lines.append(f'{signature} = {body}')
        return '\n'.join(lines)


def instance_description(function: Function, body: str, statics: list[tuple[Function, str]]) -> str | None:
    """The description of an instance function `x(args) = Companion.x(this, args)`, from the static function it calls."""
    call = call_parts(body)
    if not call:
        return None
    callee, args = call
    if not callee.startswith(('Companion.', 'Expression.')) or not args or args[0] != 'this':
        return None
    name = callee.split('.')[-1]
    params = {p.name: p.type for p in function.parameters}
    for static, static_body in statics:
        if static.name != name or len(static.parameters) != len(args):
            continue
        if not static.parameters[0].type.endswith('Expression'):
            continue
        if all(params.get(a.lstrip('*')) == p.type or (a.lstrip('*') not in params) for a, p in zip(args[1:], static.parameters[1:])):
            described = describe(static, static_body)
            first = static.parameters[0].name
            renamed = {p.name: a.lstrip('*') for p, a in zip(static.parameters[1:], args[1:])}
            described = re.sub(r'\[(\w+)\]', lambda m: 'this expression' if m.group(1) == first else f'[{renamed.get(m.group(1), m.group(1))}]', described)
            described = described.replace('the field this expression', 'this expression')
            return described
    return None


def generate_expression(source: str, ref: str) -> tuple[str, list[str], list[str]]:
    body, _ = class_body(source, r'^abstract class Expression internal constructor\(\)')
    companion, _ = class_body(body, r'^  companion object')
    instance = [f for f in functions(body, 2) if 'abstract' not in f.modifiers and 'override' not in f.modifiers and not (set(f.modifiers) & {'private', 'internal'})]
    static = [f for f in functions(companion, 4) if 'abstract' not in f.modifiers and f.name not in REPLACED_HELPERS]
    generator = Generator('Expression', {'instance': instance, 'static': static})
    rendered_static = []
    static_bodies = []
    for function in static:
        text = generator.render(function, '        ', True)
        if text:
            rendered_static.append(text)
            if function.is_public:
                static_bodies.append((function, drop_evaluation_functions(OVERRIDES.get((function.name, tuple(p.type for p in function.parameters)), (function.body, ''))[0])))
    rendered_instance = []
    for function in instance:
        text = generator.render(function, '    ', False)
        if not text:
            continue
        better = instance_description(function, drop_evaluation_functions(function.body), static_bodies)
        if better:
            text = re.sub(r'^(\s*)/\*\* .*? \*/', lambda m: f'{m.group(1)}/** {better}{" Beta in the Android SDK." if "@Beta" in function.annotations else ""} */', text, count=1)
        rendered_instance.append(text)
    out = [HEADER.format(file=f'{SOURCE_PATH}/expressions.kt', ref=ref)]
    out.append('package com.google.firebase.firestore.pipeline\n')
    out.append('\n'.join([
        'import com.google.firebase.Timestamp',
        'import com.google.firebase.firestore.Blob',
        'import com.google.firebase.firestore.DocumentReference',
        'import com.google.firebase.firestore.FieldPath',
        'import com.google.firebase.firestore.FieldValue',
        'import com.google.firebase.firestore.GeoPoint',
        'import com.google.firebase.firestore.Pipeline',
        'import com.google.firebase.firestore.VectorValue',
        'import kotlin.jvm.JvmStatic',
    ]) + '\n')
    out.append(EXPRESSION_KDOC)
    out.append('public abstract class Expression internal constructor() {')
    out.append('\n\n'.join(rendered_instance))
    out.append('')
    out.append('    public companion object {')
    out.append(COMPANION_HELPERS)
    out.append('\n\n'.join(rendered_static))
    out.append('    }')
    out.append('}')
    return '\n'.join(out) + '\n', generator.errors, generator.skipped


def generate_aggregate(source: str, ref: str) -> tuple[str, list[str], list[str]]:
    body, _ = class_body(source, r'^class AggregateFunction')
    companion, _ = class_body(body, r'^  companion object')
    instance = [f for f in functions(body, 2) if f.is_public]
    static = [f for f in functions(companion, 4) if f.is_public]
    generator = Generator('AggregateFunction', {'instance': instance, 'static': static})
    rendered_static = [t for t in (generator.render(f, '        ', True) for f in static) if t]
    rendered_instance = [t for t in (generator.render(f, '    ', False) for f in instance) if t]
    out = [HEADER.format(file=f'{SOURCE_PATH}/aggregates.kt', ref=ref)]
    out.append('package com.google.firebase.firestore.pipeline\n')
    out.append('import kotlin.jvm.JvmStatic\n')
    out.append(AGGREGATE_KDOC)
    out.append('''public class AggregateFunction private constructor(
    internal val name: String,
    internal val params: Array<out Expression>,
    internal val options: InternalOptions = InternalOptions.EMPTY,
) {
    private constructor(name: String) : this(name, emptyArray<Expression>())
    private constructor(name: String, expr: Expression) : this(name, arrayOf(expr))
    private constructor(name: String, fieldName: String) : this(name, Expression.field(fieldName))
''')
    out.append('\n\n'.join(rendered_instance))
    out.append('')
    out.append('    public companion object {')
    out.append('\n\n'.join(rendered_static))
    out.append('    }')
    out.append('}')
    return '\n'.join(out) + '\n', generator.errors, generator.skipped


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--ref', help='the firebase-android-sdk git ref (default: androidSdk.apiRef in gradle.properties)')
    parser.add_argument('--source-dir', help='a directory with expressions.kt and aggregates.kt, instead of downloading them')
    args = parser.parse_args()
    ref = args.ref or read_ref()
    sources = fetch_sources(ref, args.source_dir)
    errors, skipped = [], []
    for name, (text, file_errors, file_skipped) in {
        'Expression.kt': generate_expression(sources['expressions.kt'], ref),
        'AggregateFunction.kt': generate_aggregate(sources['aggregates.kt'], ref),
    }.items():
        errors += file_errors
        skipped += file_skipped
        with open(os.path.join(OUTPUT, name), 'w', encoding='utf-8') as out:
            out.write(text)
    for member in skipped:
        print(f'left out (Android-only parameter type): {member}')
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        raise SystemExit(1)


if __name__ == '__main__':
    main()
